#!/usr/bin/env bash
# Shebang — запускати файл інтерпретатором bash (env шукає bash у PATH).

# set -e / -u / -o pipefail — зупиняти скрипт при помилці, забороняти
# неоголошені змінні, ловити падіння всередині конвеєрів (|). Деталі — у backup.sh.
set -euo pipefail

# $# — кількість аргументів, переданих скрипту.
# Якщо менше одного (тобто не вказали ім'я файлу бекапу) — показуємо підказку й виходимо.
if [ $# -lt 1 ]; then
  # >&2 — вивести текст у потік помилок (stderr), а не у звичайний вивід.
  echo "Usage: $0 <backup_file.sql>" >&2
  # exit 1 — завершити з кодом 1 (помилка), щоб виклик скрипта знав про невдачу.
  exit 1
fi

# $1 — перший аргумент (ім'я файлу бекапу), зберігаємо у змінну file.
file="$1"

# Головна команда відновлення:
#   docker exec -i postgres -> виконати в контейнері postgres, -i тримає stdin відкритим
#   psql                    -> клієнт PostgreSQL, що виконує SQL із файлу
#   -U postgres             -> від імені користувача postgres
#   -d image_hosting        -> у яку базу даних заливаємо дамп
#   -f /backups/${file}     -> прочитати SQL з файлу всередині контейнера
# Файл береться зі змонтованої папки /backups (= наша ./backups на хості).
docker exec -i postgres psql -U postgres -d image_hosting -f "/backups/${file}"

# Дійшли сюди = відновлення без помилок. Повідомляємо про успіх.
echo "OK: відновлено з backups/${file}"
