#!/usr/bin/env bash
# Рядок вище (shebang) — каже системі, чим запускати файл: інтерпретатором bash.
# env знаходить bash у PATH, тож скрипт працює на різних дистрибутивах Linux.

# set -e  -> якщо будь-яка команда впаде (поверне не 0) — скрипт одразу зупиниться.
# set -u  -> звернення до неоголошеної змінної = помилка (захист від опечаток).
# set -o pipefail -> якщо команда в конвеєрі (|) впала, весь конвеєр вважається невдалим.
set -euo pipefail

# Поточна дата/час у форматі РРРР-ММ-ДД_ГГХХСС, напр. 2025-01-24_153000.
# $( ... ) — підстановка команди: результат date підставляється в змінну ts.
ts=$(date +%Y-%m-%d_%H%M%S)

# Складаємо ім'я файлу бекапу. ${ts} — вставка значення змінної в рядок.
file="backup_${ts}.sql"

# Головна команда:
#   docker exec postgres   -> виконати команду всередині контейнера з ім'ям postgres
#   pg_dump                -> утиліта PostgreSQL, що вивантажує всю БД у SQL
#   -U postgres            -> від імені користувача postgres
#   -d image_hosting       -> яку базу даних бекапимо
#   -f /backups/${file}    -> записати дамп у файл всередині контейнера
# Папка /backups змонтована на хост (./backups), тож файл одразу з'являється у нас.
docker exec postgres pg_dump -U postgres -d image_hosting -f "/backups/${file}"

# Якщо дійшли сюди — попередня команда не впала (бо set -e). Друкуємо шлях до бекапу.
echo "OK: backups/${file}"
